"""Deterministic extraction of Jan Aadhaar identifiers/credentials out of a
citizen's raw message - regex/digit-counting only, NO LLM call anywhere in
this module. Used exclusively by janaadhaar_handle_node (app/chat.py) while
a verification sub-flow is in progress, so a raw Jan Aadhaar ID or OTP is
parsed by plain code instead of ever being sent to a model as input.
"""

import re

_DIGIT_RE = re.compile(r"\d")


def digits_only(text: str) -> str:
    """Strip everything but digits - citizens type IDs/OTPs with spaces or
    dashes ("1234 5678 90") about as often as not."""
    return "".join(_DIGIT_RE.findall(text))


def extract_jan_aadhaar_id(text: str) -> str | None:
    """A Jan Aadhaar ID is exactly 10 digits (Jan Aadhaar Integration
    Document v1.8, S5 parameter table). None if the message doesn't reduce
    to exactly 10 digits once separators are stripped."""
    digits = digits_only(text)
    return digits if len(digits) == 10 else None


def extract_otp(text: str) -> str | None:
    """OTPs generated by generate_otp() are 6 digits."""
    digits = digits_only(text)
    return digits if len(digits) == 6 else None


_CANDIDATE_NUMBER_RE = re.compile(r"\d[\d\s\-]*\d|\d")


def scrub_jan_aadhaar_ids(text: str) -> str:
    """Redacts any bare 10-digit run (a Jan Aadhaar ID's exact length, per
    the Integration Document v1.8 S5 parameter table) found ANYWHERE in
    free text - not just when the graph already expects one.

    Found live (2026-08-25): every OTHER function in this module is only
    ever called from inside janaadhaar_handle_node, which only runs once
    pending_janaadhaar_step is already set - so a citizen who pastes their
    ID UNPROMPTED, in the same message that first raises a citizen_status
    need (e.g. "mera jan aadhaar id 1234567890 hai, meri pension ka status
    batao"), has that ID sent straight to extract_profile_node/
    extract_need_node's LLM prompts before the graph even knows a Jan
    Aadhaar flow is relevant - then persisted into conversation_history and
    server logs in cleartext, replayed into every later prompt too via the
    rolling history window. This is meant to run in normalize_node, on
    every turn, regardless of what step (if any) is pending - a general
    content-based safety net under the existing state-machine-gated one,
    not a replacement for it.

    Deliberately 10-digit runs ONLY, not 6-digit (OTP length) - a 6-digit
    number is indistinguishable from an ordinary income figure a citizen
    might legitimately state ("meri income 200000 hai"), and blindly
    redacting those would break income extraction for no real benefit: an
    OTP has no realistic reason to be pasted UNPROMPTED outside the gated
    flow anyway, since it only exists after generate_otp() sends one in
    response to a request already inside that flow. A 10-digit run this
    catches might occasionally be an ordinary phone number rather than a
    Jan Aadhaar ID - redacting it anyway is a harmless false positive, not
    a cost, since this app has no use for a phone number either way."""
    def _replace(match):
        digits = digits_only(match.group(0))
        return "[possible Jan Aadhaar ID redacted]" if len(digits) == 10 else match.group(0)
    return _CANDIDATE_NUMBER_RE.sub(_replace, text)


# Checked BEFORE the no/yes lists below (found live testing this directly:
# "mujhe pata nahi" - "I don't know" - contains the bare substring "nahi"
# and got misread as a flat "No" without this check first, even though the
# citizen wasn't declining at all, just unsure) - "don't know" phrases must
# never fall through to the "no" substring match just because "nahi"/"pata
# nahi" happens to appear inside them.
_DONT_KNOW_PHRASES = (
    "pata nahi", "nahi pata", "pta nahi", "nahi pta", "maloom nahi", "nahi maloom",
    "malum nahi", "confuse", "confusion", "पता नहीं", "मालूम नहीं",
)
# Checked in this order (no before yes), same simple substring-matching
# style as app/chat.py's _is_none_of_these, not an LLM call, since this only
# ever runs on the citizen's response to a plain yes/no consent question,
# not free-form text.
_NO_PHRASES = ("nahi", "nahin", "mat karo", "nahi chahiye", "no", "नहीं", "मत करो", "ना")
_YES_PHRASES = ("haan", "han", "haa", "ji haan", "ji han", "theek hai", "sahi hai", "ok", "yes", "हाँ", "हां", "जी हाँ", "ठीक है")

# Bare 2-letter "ha"/"na" (2026-08-26, found live) - every _YES_PHRASES entry
# is 3+ letters, so a citizen replying with just "ha" could never match via
# substring containment (the phrase has to fit INSIDE the text, and "ha" is
# too short to contain "haan"/"han"/"haa") - three straight "ha" replies to
# a consent question got read as unclear every time, hit the attempt cap,
# and aborted the whole flow. Fixed with WORD-BOUNDARY matching, not a bare
# substring check like the phrases above - "ha" is a substring of "hai"
# (is/am/are) and "chahiye" (want), both extremely common words, so a naive
# `"ha" in normalized` would wrongly read most ordinary Hindi/Hinglish
# messages as consent. \bha\b only matches "ha" as its own token.
_SHORT_YES_RE = re.compile(r"\bha\b")
_SHORT_NO_RE = re.compile(r"\bna\b")


def extract_consent(text: str) -> bool | None:
    """Deterministic yes/no parse of a reply to the Jan Aadhaar consent
    question (janaadhaar_handle_node's 'awaiting_consent' step) - True/False
    if a clear answer is found, None if the message doesn't match either
    list, or reads as genuine uncertainty ("pata nahi") rather than a firm
    no (re-ask rather than guess in either case)."""
    normalized = text.strip().lower()
    if any(phrase in normalized for phrase in _DONT_KNOW_PHRASES):
        return None
    if any(phrase in normalized for phrase in _NO_PHRASES) or _SHORT_NO_RE.search(normalized):
        return False
    if any(phrase in normalized for phrase in _YES_PHRASES) or _SHORT_YES_RE.search(normalized):
        return True
    return None


# Checked BEFORE treating a non-6-digit message as a wrong OTP guess
# (2026-08-26, found live) - "OTP nahi mila"/"dobara bhejo" used to fall
# straight through to extract_otp() returning None, which janaadhaar_handle_
# node then treated EXACTLY like a wrong guess: shown a misleading "that
# OTP doesn't look correct" message, AND it silently burned one of only 3
# total attempts before a full abort - for a delivery problem that isn't
# the citizen's mistake at all.
#
# First version (exact multi-word phrases like "phir se bhejo"/"dobara
# bhejo") missed real live input entirely: "firse bheje" and "firse otp
# bhejje" - Hinglish spelling varies too much ("phir se"/"fir se"/"firse",
# "bhejo"/"bheje"/"bhejje") for a fixed-phrase list to keep up. Rebuilt as
# STEM co-occurrence instead: a "send" stem (bhej.../भेज.../send) alongside
# an "again"/"otp" stem, in either order, regardless of exact spelling or
# spacing between them - covers the realistic spelling variance a full
# phrase list can't.
#
# "nahi mila"/"nahi aaya" alone are NOT included as bare stems (caught by
# my own test before shipping the first version) - "samajh nahi aaya" (I
# didn't understand) contains that exact substring and would wrongly
# trigger a resend for an unrelated confusion message. Kept scoped to the
# separate _RESEND_NOT_RECEIVED_PHRASES check below, which requires "otp"
# in the same phrase.
_RESEND_SEND_STEMS = ("bhej", "send", "भेज")
_RESEND_TRIGGER_STEMS = ("phir", "fir", "dobara", "dubara", "wapis", "again", "otp", "फिर", "दोबारा", "दुबारा", "ओटीपी")
_RESEND_NOT_RECEIVED_PHRASES = (
    "otp nahi mila", "otp nahi aaya", "otp nahi aya", "ओटीपी नहीं मिला", "ओटीपी नहीं आया",
)


def extract_resend_request(text: str) -> bool:
    """Whether this message is asking for the OTP to be sent again, rather
    than attempting to answer with one."""
    normalized = text.strip().lower()
    if "resend" in normalized or "re-send" in normalized:
        return True
    if any(phrase in normalized for phrase in _RESEND_NOT_RECEIVED_PHRASES):
        return True
    has_send_stem = any(stem in normalized for stem in _RESEND_SEND_STEMS)
    has_trigger_stem = any(stem in normalized for stem in _RESEND_TRIGGER_STEMS)
    return has_send_stem and has_trigger_stem
