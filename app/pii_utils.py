"""Deterministic extraction of Jan Aadhaar identifiers/credentials out of a
citizen's raw message - regex/digit-counting only, NO LLM call anywhere in
this module. Used exclusively by janaadhaar_handle_node (app/chat.py) while
a verification sub-flow is in progress, so a raw Jan Aadhaar ID or OTP is
parsed by plain code instead of ever being sent to a model as input.

Also home to redact_digits(), which app/main.py runs over every message
before it reaches the server log.

Design notes (2026-08-20 audit fixes):
  - ID/OTP extraction looks for ONE contiguous digit group (spaces/dashes
    allowed between digits), not "all digits in the message concatenated" -
    "umar 65, income 2 lakh, 2024" must not read as a 6-digit OTP, and
    "OTP 123456 aaya, 2 minute pehle" must still be accepted.
  - Devanagari digits (०-९) are mapped to ASCII first.
  - Consent parsing is whole-word (tokenised), so bare "na" no longer
    matches inside करना/नाम/अपना and "han" no longer matches Hanuman.
"""

import re

_DEVANAGARI_DIGITS = str.maketrans("०१२३४५६७८९", "0123456789")

_DIGIT_RE = re.compile(r"\d")

# One contiguous run of N digits, optionally separated by single spaces or
# dashes, not touching any other digit on either side. Built per-length.
def _digit_group_re(n: int) -> re.Pattern:
    return re.compile(rf"(?<![\d])(?:\d[ -]?){{{n - 1}}}\d(?![\d])")


_OTP_RE = _digit_group_re(6)
_JAN_ID_RE = _digit_group_re(10)
# Any 6- or 10-digit group (with separators) -> "XXXXXX" for logging.
_REDACT_RE = re.compile(r"(?<![\d])(?:\d[ -]?){5,9}\d(?![\d])")


def normalize_digits(text: str) -> str:
    """Map Devanagari digits to ASCII so every regex below sees one script."""
    return (text or "").translate(_DEVANAGARI_DIGITS)


def digits_only(text: str) -> str:
    """Strip everything but digits - citizens type IDs/OTPs with spaces or
    dashes ("1234 5678 90") about as often as not."""
    return "".join(_DIGIT_RE.findall(normalize_digits(text)))


def _first_group(pattern: re.Pattern, text: str, length: int) -> str | None:
    for match in pattern.finditer(normalize_digits(text)):
        digits = "".join(_DIGIT_RE.findall(match.group(0)))
        if len(digits) == length:
            return digits
    return None


def extract_jan_aadhaar_id(text: str) -> str | None:
    """A Jan Aadhaar ID is exactly 10 digits (Jan Aadhaar Integration
    Document v1.8, S5 parameter table). Returns the first contiguous
    10-digit group (separators allowed), or None."""
    return _first_group(_JAN_ID_RE, text, 10)


def extract_otp(text: str) -> str | None:
    """OTPs generated by generate_otp() are 6 digits. Returns the first
    contiguous 6-digit group (separators allowed), or None."""
    return _first_group(_OTP_RE, text, 6)


def redact_digits(text: str) -> str:
    """Replace every 6-to-10-digit group (with optional separators) with
    "XXXXXX" so OTPs, Jan Aadhaar IDs and phone numbers never hit a log."""
    if not text:
        return text
    return _REDACT_RE.sub("XXXXXX", normalize_digits(text))


# ---------------------------------------------------------------------------
# Consent / cancel parsing
# ---------------------------------------------------------------------------

_TOKEN_RE = re.compile(r"[\wऀ-ॿ]+")


def _tokens(text: str) -> list[str]:
    return _TOKEN_RE.findall((text or "").lower())


def _contains_phrase(tokens: list[str], phrase: tuple[str, ...]) -> bool:
    n = len(phrase)
    return any(tuple(tokens[i:i + n]) == phrase for i in range(len(tokens) - n + 1))


def _phrases(*items: str) -> tuple[tuple[str, ...], ...]:
    return tuple(tuple(item.split()) for item in items)


# Checked first: "don't know" must never fall through to a "no" just
# because "nahi" appears inside it.
_DONT_KNOW = _phrases(
    "pata nahi", "nahi pata", "pta nahi", "nahi pta", "maloom nahi", "nahi maloom",
    "malum nahi", "confuse", "confused", "confusion", "पता नहीं", "नहीं पता", "मालूम नहीं",
)

_YES = _phrases(
    "haan", "han", "haa", "ha", "hanji", "haanji", "ji", "ji haan", "ji han", "bilkul", "zaroor",
    "jarur", "zarur", "kar do", "karo", "kijiye", "sure", "yeah", "yep", "yes", "theek hai",
    "thik hai", "sahi hai", "ok", "okay", "okk", "haan ji",
    "हाँ", "हां", "हा", "जी", "जी हाँ", "जी हां", "बिल्कुल", "बिलकुल", "ठीक है", "सही है", "करो", "कर दो",
    "जरूर", "ज़रूर",
)

_NO = _phrases(
    "no", "nope", "nahi", "nahin", "nhi", "na", "mat", "mat karo", "rehne do", "rahne do",
    "chhodo", "chodo", "cancel", "nahi chahiye", "nahi karna",
    "नहीं", "नही", "ना", "मत", "मत करो", "रहने दो", "छोड़ो", "छोड़ दो", "नहीं करना", "नहीं चाहिए",
)

# Explicit negation of the verification itself - beats a trailing "haan".
_EXPLICIT_NO = _phrases(
    "nahi karna", "nahi karni", "mat karo", "mat kijiye", "nahi chahiye", "nahi karwana",
    "rehne do", "rahne do", "chhodo", "chodo", "cancel",
    "नहीं करना", "मत करो", "नहीं चाहिए", "रहने दो", "छोड़ो", "छोड़ दो",
)
# "koi problem nahi" / "koi dikkat nahi" / "no problem" - these contain a
# negative token but are affirmative idioms.
_AFFIRMATIVE_IDIOMS = _phrases(
    "koi problem nahi", "koi dikkat nahi", "koi baat nahi", "no problem", "koi problem nhi",
    "कोई दिक्कत नहीं", "कोई बात नहीं", "कोई समस्या नहीं",
)


def _strip_phrases(tokens: list[str], phrases) -> list[str]:
    out = list(tokens)
    for phrase in phrases:
        n = len(phrase)
        i = 0
        while i <= len(out) - n:
            if tuple(out[i:i + n]) == phrase:
                del out[i:i + n]
            else:
                i += 1
    return out


def extract_consent(text: str) -> bool | None:
    """Deterministic yes/no parse of a reply to the Jan Aadhaar consent
    question. True/False on a clear answer, None when unclear (re-ask).

    Whole-word matching; "don't know" -> None; affirmative idioms that
    contain a negative word ("haan, koi problem nahi") -> True; explicit
    negation of the verification ("nahi karna ... haan?") -> False; a
    message containing both a plain yes and a plain no with no clear
    structure -> None."""
    tokens = _tokens(text)
    if not tokens:
        return None
    if any(_contains_phrase(tokens, p) for p in _DONT_KNOW):
        return None
    if any(_contains_phrase(tokens, p) for p in _EXPLICIT_NO):
        return False

    remaining = _strip_phrases(tokens, _AFFIRMATIVE_IDIOMS)
    had_idiom = len(remaining) != len(tokens)

    has_yes = any(_contains_phrase(remaining, p) for p in _YES)
    has_no = any(_contains_phrase(remaining, p) for p in _NO)

    if has_yes and has_no:
        return None
    if has_no:
        return False
    if has_yes or had_idiom:
        return True
    return None


_CANCEL = _phrases(
    "cancel", "skip", "rehne do", "rahne do", "chhodo", "chodo", "chhod do", "baad mein", "baad me",
    "nahi karna", "nahi karni", "band karo", "wait", "ruko", "rukiye", "stop", "abhi nahi",
    "रहने दो", "छोड़ो", "छोड़ दो", "बाद में", "नहीं करना", "बंद करो", "रुको", "रुकिए", "अभी नहीं",
)


def extract_cancel(text: str) -> bool:
    """True when the citizen wants out of the Jan Aadhaar flow at any step
    ("cancel", "rehne do", "baad mein", "ruko", ...). Whole-word match."""
    tokens = _tokens(text)
    return any(_contains_phrase(tokens, p) for p in _CANCEL)
